#!/usr/bin/env node
import fs from "node:fs";
import crypto from "node:crypto";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const eventScript = path.join(scriptDir, "wmux-agent-event");
const titleScript = path.join(scriptDir, "wmux-title");
const questionContractPath = path.join(scriptDir, "opencode-question-contract.json");
const questionContract = readQuestionContract();

const renderIntegration = (source) => "// Generated by wmux-hooks. Changes will be overwritten.\n" + source
  .replaceAll(JSON.stringify("__WMUX_EVENT_SCRIPT__"), JSON.stringify(eventScript))
  .replaceAll(JSON.stringify("__WMUX_TITLE_SCRIPT__"), JSON.stringify(titleScript))
  .replaceAll(JSON.stringify("__WMUX_BROKER_SCRIPT__"), JSON.stringify(path.join(scriptDir, "wmux-agent-input-broker")))
  .replaceAll(JSON.stringify("__WMUX_QUESTION_CONTRACT_PATH__"), JSON.stringify(questionContractPath))
  .replaceAll(JSON.stringify("__WMUX_QUESTION_CONTRACT__"), JSON.stringify(JSON.stringify(questionContract ?? null)));

const claudeHookCommand = `${eventScript} --agent claude --claude-hook`;
const codexHookCommand = `${eventScript} --agent codex --codex-hook`;

const usage = () => {
  console.error(`Usage:
  wmux-hooks install claude
  wmux-hooks install codex [--agent-titles]
  wmux-hooks install opencode
  wmux-hooks install prime-agent
  wmux-hooks status
`);
};

const readJson = (filePath) => {
  if (!fs.existsSync(filePath)) return {};
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
};

function readQuestionContract() {
  try {
    const value = JSON.parse(fs.readFileSync(questionContractPath, "utf8"));
    const claimed = value?.canonicalContractDigest;
    const unsigned = structuredClone(value);
    delete unsigned.canonicalContractDigest;
    const canonicalize = (input) => Array.isArray(input)
      ? input.map(canonicalize)
      : input && typeof input === "object"
        ? Object.fromEntries(Object.keys(input).sort().map((key) => [key, canonicalize(input[key])]))
        : input;
    const actual = crypto.createHash("sha256").update(JSON.stringify(canonicalize(unsigned))).digest("hex");
    if (value?.schemaVersion !== 4 || value.handshakeSchema !== 4 || value.openCodeRelease !== value.sdkVersion
      || typeof value.sdkVersion !== "string" || typeof value.compatibilityFingerprint !== "string"
      || value.healthSource !== "plugin.injectedTransport:/global/health"
      || value.healthCall !== "structuredClient.global.health({ signal })"
      || value.eventEnvelope !== "legacy-properties"
      || !/^[a-f0-9]{64}$/.test(claimed) || claimed !== actual) throw new Error("invalid OpenCode question contract");
    return value;
  } catch {
    return undefined;
  }
}

const writeJson = (filePath, data) => {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`);
};

const hasCommand = (items, command) =>
  items.some((entry) => entry?.hooks?.some((hook) => hook?.type === "command" && hook?.command === command));

const addHook = (settings, eventName, command, options = {}) => {
  settings.hooks ??= {};
  settings.hooks[eventName] ??= [];
  if (hasCommand(settings.hooks[eventName], command)) return false;
  settings.hooks[eventName].push({
    hooks: [
      {
        type: "command",
        command,
        timeout: 30,
        ...options,
      },
    ],
  });
  return true;
};

const claudeSkillPath = () => path.join(os.homedir(), ".claude", "skills", "wmux", "SKILL.md");

const claudeSkill = () => `---
name: wmux
description: Delegate visible, durable OpenCode, Codex, Claude, or Prime Agent work to a wmux machine.
---

<!-- Generated by wmux-hooks. Changes will be overwritten. -->

# wmux delegation

Use \`wmuxctl\` when work should run visibly on another configured wmux machine.
If it is not on \`PATH\`, invoke ${JSON.stringify(path.join(scriptDir, "wmuxctl"))} directly.

1. Run \`wmuxctl machines\` and select an exact reachable machine id.
2. Put a substantial prompt in a private temporary file, then run:

   \`wmuxctl delegate codex MACHINE --directory /absolute/project --prompt-file FILE --title "Task title"\`

   Replace \`codex\` with \`claude\`, \`opencode\`, or \`prime-agent\` when requested.
3. Omit \`--write-access\` for Codex read-only or Claude plan mode. Add it only when edits are intended. OpenCode and Prime Agent require it because they cannot enforce read-only delegation.
4. Add \`--unattended\` only when the user explicitly authorized unattended execution. Prime Agent requires both flags because it has no approval prompts; this does not enable its unrelated autonomous continuation mode.
5. One-shot delegations close after success by default. Use \`--retain-workspace\` only when the successful terminal must remain available, and report the returned direct URL for anything left open.
6. Review waits default to 30 minutes and change/deploy waits default to two hours. A wait timeout detaches the controller without stopping the worker; reconcile the returned run ID before retrying.

Never put a long or sensitive prompt directly in shell arguments. Failed, stopped, and timed-out one-shot workspaces remain visible for inspection and expire after 24 hours unless explicitly retained.
`;

const installClaudeSkill = () => {
  const skillPath = claudeSkillPath();
  const skill = claudeSkill();
  if (fs.existsSync(skillPath)) {
    const current = fs.readFileSync(skillPath, "utf8");
    if (current === skill) return { changed: false, managed: true, skillPath };
    if (!current.includes("Generated by wmux-hooks")) return { changed: false, managed: false, skillPath };
  }
  fs.mkdirSync(path.dirname(skillPath), { recursive: true });
  fs.writeFileSync(skillPath, skill);
  return { changed: true, managed: true, skillPath };
};

const installClaude = () => {
  const settingsPath = path.join(os.homedir(), ".claude", "settings.json");
  const settings = readJson(settingsPath);
  const changed = [
    addHook(settings, "UserPromptSubmit", claudeHookCommand),
    addHook(settings, "Stop", claudeHookCommand),
    addHook(settings, "Notification", claudeHookCommand),
  ].some(Boolean);
  if (changed) writeJson(settingsPath, settings);
  const installedSkill = installClaudeSkill();
  console.log(`${changed ? "Installed" : "Already installed"} Claude hooks in ${settingsPath}`);
  console.log(installedSkill.managed
    ? `${installedSkill.changed ? "Installed" : "Already installed"} Claude wmux skill at ${installedSkill.skillPath}`
    : `Preserved existing unmanaged Claude skill at ${installedSkill.skillPath}`);
  console.log(`Hook command: ${claudeHookCommand}`);
};

const installCodex = () => {
  const settingsPath = path.join(os.homedir(), ".codex", "hooks.json");
  const settings = readJson(settingsPath);
  const managedCommand = /^\S*\/wmux-agent-event --agent codex --codex-hook(?: --no-title)?$/;
  const events = ["UserPromptSubmit", "PreToolUse", "Stop"];
  const agentTitles = process.argv.includes("--agent-titles") || events.some((eventName) =>
    (settings.hooks?.[eventName] ?? []).some((group) => (group.hooks ?? []).some((hook) =>
      hook.type === "command" && typeof hook.command === "string"
      && managedCommand.test(hook.command) && hook.command.endsWith(" --no-title"))));
  // Upgrade only wmux's generated commands, including an earlier install path.
  // Preserve unrelated hooks and preserve an existing agent-title opt-in when
  // a routine reinstall omits the flag.
  let migrated = false;
  for (const eventName of events) {
    for (const group of settings.hooks?.[eventName] ?? []) {
      for (const hook of group.hooks ?? []) {
        if (hook.type !== "command" || typeof hook.command !== "string"
          || !managedCommand.test(hook.command)) continue;
        const command = codexHookCommand + (agentTitles ? " --no-title" : "");
        if (hook.command !== command) { hook.command = command; migrated = true; }
      }
    }
  }
  const command = codexHookCommand + (agentTitles ? " --no-title" : "");
  const changed = [
    migrated,
    addHook(settings, "UserPromptSubmit", command, {
      statusMessage: "Updating wmux workspace",
    }),
    addHook(settings, "PreToolUse", command, {
      statusMessage: "Updating wmux workspace",
    }),
    addHook(settings, "Stop", command, {
      statusMessage: "Summarizing wmux workspace",
    }),
  ].some(Boolean);
  if (changed) writeJson(settingsPath, settings);
  console.log(`${changed ? "Installed" : "Already installed"} Codex hooks in ${settingsPath}`);
  console.log(`Hook command: ${command}`);
  console.log("Run /hooks inside Codex to review and trust this hook before expecting it to run.");
};

const opencodePluginPath = () => path.join(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), ".config"), "opencode", "plugins", "wmux.ts");
const opencodeConfigRoot = () => path.resolve(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), ".config"));

const assertNoSymlinkComponents = (target) => {
  const resolved = path.resolve(target);
  const parsed = path.parse(resolved);
  let current = parsed.root;
  for (const segment of resolved.slice(parsed.root.length).split(path.sep).filter(Boolean)) {
    current = path.join(current, segment);
    if (!fs.existsSync(current)) continue;
    if (fs.lstatSync(current).isSymbolicLink()) throw new Error("OpenCode plugin path ancestors must not use symlinks");
  }
};

const assertSafePluginDirectory = (directory) => {
  const resolved = path.resolve(directory);
  const stat = fs.lstatSync(resolved);
  if (!stat.isDirectory() || stat.isSymbolicLink() || fs.realpathSync(resolved) !== resolved) {
    throw new Error("OpenCode plugin directory ancestors must be non-symlink directories");
  }
  if (typeof process.getuid === "function" && stat.uid !== process.getuid()) {
    throw new Error("OpenCode plugin directory ancestors must be owned by the current user");
  }
  if ((stat.mode & 0o022) !== 0) throw new Error("OpenCode plugin directory ancestors must not be group/world writable");
};

const opencodePlugin = () => renderIntegration(__WMUX_OPENCODE_SOURCE__);

const installOpenCode = () => {
  const pluginPath = opencodePluginPath();
  const plugin = opencodePlugin();
  const pluginDirectory = path.dirname(path.resolve(pluginPath));
  const configRoot = opencodeConfigRoot();
  if (pluginDirectory !== path.join(configRoot, "opencode", "plugins")) {
    throw new Error("OpenCode plugin path escaped the configured root");
  }
  assertNoSymlinkComponents(configRoot);
  fs.mkdirSync(configRoot, { recursive: true, mode: 0o700 });
  assertSafePluginDirectory(configRoot);
  for (const directory of [path.join(configRoot, "opencode"), pluginDirectory]) {
    assertNoSymlinkComponents(directory);
    if (!fs.existsSync(directory)) fs.mkdirSync(directory, { mode: 0o700 });
    assertSafePluginDirectory(directory);
  }
  let current = "";
  if (fs.existsSync(pluginPath)) {
    const existing = fs.lstatSync(pluginPath);
    if (!existing.isFile() || existing.isSymbolicLink() || fs.realpathSync(pluginPath) !== path.resolve(pluginPath)) {
      throw new Error("OpenCode plugin path must be a regular non-symlink file");
    }
    if (typeof process.getuid === "function" && existing.uid !== process.getuid()) {
      throw new Error("OpenCode plugin file must be owned by the current user");
    }
    if ((existing.mode & 0o022) !== 0) throw new Error("OpenCode plugin file must not be group/world writable");
    current = fs.readFileSync(pluginPath, "utf8");
    if (current !== plugin && !current.startsWith("// Generated by wmux-hooks.")) {
      throw new Error("OpenCode plugin path contains an unmanaged file");
    }
  }
  const changed = current !== plugin;
  if (changed) {
    const temporary = path.join(pluginDirectory, `.wmux.ts.${process.pid}.${crypto.randomBytes(8).toString("hex")}.tmp`);
    try {
      fs.writeFileSync(temporary, plugin, { flag: "wx", mode: 0o600 });
      fs.renameSync(temporary, pluginPath);
      fs.chmodSync(pluginPath, 0o600);
    } catch (error) {
      fs.rmSync(temporary, { force: true });
      throw error;
    }
  } else if ((fs.statSync(pluginPath).mode & 0o777) !== 0o600) {
    fs.chmodSync(pluginPath, 0o600);
  }
  console.log(`${changed ? "Installed" : "Already installed"} OpenCode plugin at ${pluginPath}`);
  console.log(`Hook command: ${eventScript} --agent opencode --opencode-hook`);
  console.log(`Plugin sha256: ${crypto.createHash("sha256").update(plugin).digest("hex")}`);
};

const primeAgentExtensionPath = () => path.join(os.homedir(), ".prime", "agent", "extensions", "wmux.ts");

const primeAgentExtension = () => renderIntegration(__WMUX_PRIME_AGENT_SOURCE__);

const installPrimeAgent = () => {
  const extensionPath = primeAgentExtensionPath();
  const extension = primeAgentExtension();
  if (fs.existsSync(extensionPath)) {
    const current = fs.readFileSync(extensionPath, "utf8");
    if (current === extension) {
      console.log(`Already installed Prime Agent extension at ${extensionPath}`);
      return;
    }
    if (!current.startsWith("// Generated by wmux-hooks.")) {
      console.log(`Preserved existing unmanaged Prime Agent extension at ${extensionPath}`);
      return;
    }
  }
  fs.mkdirSync(path.dirname(extensionPath), { recursive: true });
  fs.writeFileSync(extensionPath, extension);
  console.log(`Installed Prime Agent extension at ${extensionPath}`);
  console.log(`Hook command: ${eventScript} --agent prime-agent --prime-agent-hook`);
};

const status = () => {
  const claudePath = path.join(os.homedir(), ".claude", "settings.json");
  const claudeSettings = readJson(claudePath);
  const claudeInstalled = ["UserPromptSubmit", "Stop", "Notification"].every((eventName) =>
    hasCommand(claudeSettings.hooks?.[eventName] ?? [], claudeHookCommand),
  );
  const claudeSkillFile = claudeSkillPath();
  const claudeSkillInstalled = fs.existsSync(claudeSkillFile) && fs.readFileSync(claudeSkillFile, "utf8") === claudeSkill();
  const codexPath = path.join(os.homedir(), ".codex", "hooks.json");
  const codexSettings = readJson(codexPath);
  const codexInstalled = ["UserPromptSubmit", "PreToolUse", "Stop"].every((eventName) =>
    hasCommand(codexSettings.hooks?.[eventName] ?? [], codexHookCommand)
    || hasCommand(codexSettings.hooks?.[eventName] ?? [], codexHookCommand + " --no-title"),
  );
  const openCodePath = opencodePluginPath();
  const expectedOpenCodePlugin = opencodePlugin();
  const expectedOpenCodeHash = crypto.createHash("sha256").update(expectedOpenCodePlugin).digest("hex");
  const installedOpenCodePlugin = fs.existsSync(openCodePath) ? fs.readFileSync(openCodePath, "utf8") : "";
  const installedOpenCodeHash = installedOpenCodePlugin
    ? crypto.createHash("sha256").update(installedOpenCodePlugin).digest("hex")
    : "";
  const openCodeInstalled = installedOpenCodePlugin === expectedOpenCodePlugin;
  const primeAgentPath = primeAgentExtensionPath();
  const primeAgentInstalled = fs.existsSync(primeAgentPath) && fs.readFileSync(primeAgentPath, "utf8") === primeAgentExtension();
  console.log(
    JSON.stringify(
      {
        claude: claudeInstalled && claudeSkillInstalled ? "installed" : "not_installed",
        claudeHooks: claudeInstalled ? "installed" : "not_installed",
        claudeSkill: claudeSkillInstalled ? "installed" : "not_installed",
        codex: codexInstalled ? "installed" : "not_installed",
        opencode: openCodeInstalled ? "installed" : "not_installed",
        primeAgent: primeAgentInstalled ? "installed" : "not_installed",
        claudeHookCommand,
        claudeSkillPath: claudeSkillFile,
        codexHookCommand,
        opencodePath: openCodePath,
        opencodeExpectedHash: expectedOpenCodeHash,
        opencodeInstalledHash: installedOpenCodeHash,
        opencodeParity: openCodeInstalled,
        primeAgentPath,
      },
      null,
      2,
    ),
  );
};

const [command, target] = process.argv.slice(2);
if (command === "install" && target === "claude") {
  installClaude();
} else if (command === "install" && target === "codex") {
  installCodex();
} else if (command === "install" && target === "opencode") {
  installOpenCode();
} else if (command === "install" && target === "prime-agent") {
  installPrimeAgent();
} else if (command === "status") {
  status();
} else if (command === "hash" && target === "opencode") {
  console.log(crypto.createHash("sha256").update(opencodePlugin()).digest("hex"));
} else {
  usage();
  process.exitCode = 2;
}

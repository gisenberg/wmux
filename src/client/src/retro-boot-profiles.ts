export interface RetroBootStep {
  text: string;
  delay: number;
  typedFrom?: number;
  tapeBorder?: "header" | "data";
  clear?: boolean;
  position?: { row: number; column: number };
  overwrite?: boolean;
  inverse?: boolean;
  postSound?: boolean;
}

export interface RetroBootProfile {
  id: string;
  name: string;
  ariaLabel: string;
  weight?: number;
  columns: number;
  rows: number;
  fontFamily: string;
  fontSize: { desktop: number; mobile: number };
  colors: {
    page: string;
    border: string;
    background: string;
    foreground: string;
  };
  bootStatus: string;
  showBootArtwork?: boolean;
  graphicalShell?: "risc-os" | "atari-st" | "lisa" | "irix" | "nextstep" | "os2";
  specialBoot?: "amiga-guru";
  boot: readonly RetroBootStep[];
  auth: {
    required: string;
    unavailable: string;
    tokenRequired: readonly string[];
    usernamePrompt: string;
    passwordPrompt: string;
    verifying: string;
    failed: string;
    granted: string;
    ready: string;
  };
}

const step = (text: string, delay = 90): RetroBootStep => ({ text, delay });
const typed = (text: string, delay = 90, prompt = ""): RetroBootStep => ({
  text: `${prompt}${text}`,
  delay,
  typedFrom: prompt.length,
});
const tapeStep = (text: string, delay: number, tapeBorder: NonNullable<RetroBootStep["tapeBorder"]>): RetroBootStep => ({
  text,
  delay,
  tapeBorder,
});
const centeredLine = (text: string, columns: number) => `${" ".repeat(Math.max(0, Math.floor((columns - text.length) / 2)))}${text}\n`;


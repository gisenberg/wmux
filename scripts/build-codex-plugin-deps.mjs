#!/usr/bin/env node
// Keep the installed plugin self-contained: it must not resolve dependencies
// from a wmux checkout or require an npm install inside Codex's plugin cache.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const source = require.resolve("ws");
const packageRoot = path.dirname(source);
const version = JSON.parse(fs.readFileSync(path.join(packageRoot, "package.json"), "utf8")).version;
const license = fs.readFileSync(path.join(packageRoot, "LICENSE"), "utf8");
const target = path.join(root, "plugins/wmux/scripts/vendor/ws.cjs");
const result = await build({
  absWorkingDir: root, entryPoints: [source], outfile: target,
  bundle: true, platform: "node", format: "cjs", target: "node22",
  write: false, minify: true, legalComments: "none",
  // Native acceleration is optional in ws. Do not load ambient native modules
  // from a plugin host; the pure-JS implementation suffices for small polls.
  define: { "process.env.WS_NO_BUFFER_UTIL": '"1"', "process.env.WS_NO_UTF_8_VALIDATE": '"1"' },
  external: ["bufferutil", "utf-8-validate"],
  banner: { js: `/* Generated by scripts/build-codex-plugin-deps.mjs.\n * ws ${version} — https://github.com/websockets/ws\n * MIT license follows. Do not edit this generated bundle.\n${license}*/` },
});
const output = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output) {
    throw new Error("Codex plugin dependency bundle is stale; run node scripts/build-codex-plugin-deps.mjs.");
  }
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, output);
}
